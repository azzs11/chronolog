"""Render the anomaly v2 results as markdown. Generated; never edited by hand."""

LABELS = {
    "always_anomalous": "Always anomalous",
    "random_same_budget": "Random, ChronoLog-H's flag rate (5 seeds)",
    "severity_rule": "Severity rule (error and critical lines)",
    "chronolog_h": "ChronoLog-H anomaly rules (v1)",
    "v2_surprise": "**v2** rare-template surprise",
    "v2_forest": "**v2** Isolation Forest (5 seeds)",
    "v2_combined": "**v2** combined (either signal, 5 seeds)",
}


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _f1(m: dict) -> str:
    if "f1_min" in m and m["f1_max"] - m["f1_min"] >= 0.0005:
        return f"{_pct(m['f1'])} ({_pct(m['f1_min'])}-{_pct(m['f1_max'])})"
    return _pct(m["f1"])


def _table(result: dict) -> str:
    rows = [
        "| Method | Precision | Recall | F1 | Episodes detected | Median delay |",
        "|---|---|---|---|---|---|",
    ]
    for key, label in LABELS.items():
        m = result["methods"][key]
        delay = "n/a" if m["median_delay_s"] is None else f"{m['median_delay_s']:+.0f} s"
        rows.append(
            f"| {label} | {_pct(m['precision'])} | {_pct(m['recall'])} | {_f1(m)} "
            f"| {m['episodes_detected']:.0f} of {m['episodes']:.0f} | {delay} |"
        )
    return "\n".join(rows)


def _sensitivity(result: dict) -> str:
    rows = ["| Rare if share below | Precision | Recall | F1 |", "|---|---|---|---|"]
    for share, m in result["rare_share_sensitivity"].items():
        rows.append(f"| {share} | {_pct(m['precision'])} | {_pct(m['recall'])} | {_pct(m['f1'])} |")
    return "\n".join(rows)


def _severity(results: dict) -> str:
    rows = [
        "| Dataset | Exact level | Error precision | Error recall | Real error share | Guessed error share |",
        "|---|---|---|---|---|---|",
    ]
    for name, result in results["datasets"].items():
        s = result["severity_from_text"]
        rows.append(
            f"| {name} | {_pct(s['exact_level_accuracy'])} | {_pct(s['error_precision'])} "
            f"| {_pct(s['error_recall'])} | {_pct(s['true_error_share'])} "
            f"| {_pct(s['guessed_error_share'])} |"
        )
    return "\n".join(rows)


def _verdict(name: str, result: dict) -> str:
    m = result["methods"]
    best = max(("v2_surprise", "v2_forest", "v2_combined"), key=lambda k: m[k]["f1"])
    bar = max(("always_anomalous", "severity_rule"), key=lambda k: m[k]["f1"])
    beats = m[best]["f1"] > m[bar]["f1"]
    rate = result["forest_flag_rate"]
    return (
        f"**Verdict ({name}):** the best v2 variant ({LABELS[best].replace('**', '')}, F1 "
        f"{_pct(m[best]['f1'])}) {'beats' if beats else 'does NOT beat'} the best trivial method "
        f"({LABELS[bar]}, {_pct(m[bar]['f1'])}). ChronoLog-H v1: {_pct(m['chronolog_h']['f1'])}. "
        f"The seed-0 forest flags {_pct(rate['fit'])} of fit units and {_pct(rate['test'])} of "
        "test units (a label-free check: a large gap means the two periods look different).\n"
    )


def render_anomaly_v2_report(results: dict) -> str:
    setup = results["setup"]
    parts = [
        "# ChronoBench: anomaly detection v2\n",
        "Does a template-based detector beat the old rules and a plain severity rule? "
        "Generated by `uv run bench anomaly-v2`; do not edit by hand.\n",
        "## Setup\n",
        f"- **Data:** {setup['dataset']}, first {setup['prefix_lines']:,} lines of each. Units: HDFS "
        f"blocks, {setup['bgl_window_s']} s BGL windows (same as `RESULTS-anomaly.md`).",
        f"- **Split by time:** the detector is fitted, without labels, on lines before the middle "
        f"line's timestamp (first {_pct(setup['fit_share'])} of lines). Every method is scored only on "
        "TEST units, those whose first line is at or after that time, so the numbers differ from "
        "`RESULTS-anomaly.md`, which scores every unit.",
        f"- **v2 rare-template surprise:** a line is flagged if its Drain template made up less than "
        f"{setup['rare_share']:g} of fit-period lines (or never appeared). Flag time: that line.",
        f"- **v2 Isolation Forest:** {setup['if_trees']} trees on {setup['if_sample']}-unit subsamples "
        f"of fit-period units, log(1 + template counts) per unit, anomalous if score > "
        f"{setup['if_threshold']} (the defaults of Liu et al. 2008 / scikit-learn). Flag time: the "
        "unit's last line, because a unit is scored once complete.",
        "- **Nothing was tuned:** every constant was fixed before the first run. The sensitivity "
        "table below was computed after seeing the results and did NOT change the headline setting.",
        f"- **Code:** v2 fingerprint `{setup['code_fingerprint']}`, ChronoLog-H fingerprint "
        f"`{setup['chronolog_h_fingerprint']}`.\n",
    ]
    for name, result in results["datasets"].items():
        parts += [
            f"## {name}\n",
            f"{result['lines']:,} lines, {result['templates']} templates. Fit units "
            f"{result['fit_units']:,}; test units {result['test_units']:,}, of which "
            f"{result['test_anomalous_units']:,} anomalous ({_pct(result['test_base_rate'])}).\n",
            _table(result) + "\n",
            _verdict(name, result),
            "Rare-template threshold, after the fact (headline: 0.0001):\n",
            _sensitivity(result) + "\n",
        ]
    parts += [
        "## Severity from text, with the real level hidden\n",
        "Many real logs carry no level (RCAEval's Online Boutique logs have none). The app then "
        "guesses one from the message text (adapter v1). Here that guess is compared with Loghub's "
        "real level on every line.\n",
        _severity(results) + "\n",
    ]
    return "\n".join(parts)

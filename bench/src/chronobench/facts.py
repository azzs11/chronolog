"""The benchmark numbers the app shows next to RootRank results, generated from bench results.

``apps/web/src/features/rootrank/benchmarkFacts.ts`` is written by ``uv run bench export-facts``
from the results files, never by hand. ``tests/test_facts.py`` fails if the committed file no
longer matches those results, so the UI cannot quote a stale number.
"""

import json
from pathlib import Path

import numpy as np

from .ablation_report import fault_kind
from .evaluate import REPO_ROOT

RESULTS_DIR = REPO_ROOT / "bench" / "results"
FACTS_PATH = REPO_ROOT / "apps" / "web" / "src" / "features" / "rootrank" / "benchmarkFacts.ts"


def _hit(rank: int | None, k: int = 3) -> float:
    return 1.0 if rank is not None and rank <= k else 0.0


def _seed_mean(ranks_by_seed: dict[str, list], mask: np.ndarray | None = None) -> float:
    per_seed = np.array([[_hit(r) for r in ranks] for ranks in ranks_by_seed.values()])
    if mask is not None:
        per_seed = per_seed[:, mask]
    return float(per_seed.mean())


def build_facts(results_dir: Path = RESULTS_DIR) -> dict[str, str]:
    rank = json.loads((results_dir / "rootrank.json").read_text())
    full = json.loads((results_dir / "rcaeval-full.json").read_text())
    auto = json.loads((results_dir / "autostart.json").read_text())
    cases = {c["case_id"]: c for c in full["cases"]}
    ids = rank["service"]["case_ids"]
    resource = np.array([fault_kind(cases[i]) == "resource fault" for i in ids])
    hand = np.mean([_hit(cases[i]["methods"]["chronolog_h"]["rank"]) for i in ids])
    pct = lambda x: f"{100 * x:.1f}%"  # noqa: E731
    return {
        "dataset": f"RCAEval RE2 and RE3, {len(ids)} incidents, logs only",
        "top3AllIncidents": pct(_seed_mean(rank["service"]["ranks_by_seed"])),
        "top3ResourceFaults": pct(_seed_mean(rank["service"]["ranks_by_seed"], resource)),
        "top3HandRules": pct(float(hand)),
        "top3TrueStart": pct(_seed_mean(auto["variants"]["true start"]["ranks_by_seed"])),
        "top3EstimatedStart": pct(_seed_mean(auto["variants"]["estimated start"]["ranks_by_seed"])),
        "evidenceFile": "bench/results/RESULTS-rootrank.md",
    }


def render_facts_ts(facts: dict[str, str]) -> str:
    lines = [f"  {key}: {json.dumps(value)}," for key, value in facts.items()]
    return (
        "// GENERATED by `uv run bench export-facts` from bench/results. Do not edit by hand.\n"
        "// What the benchmark says about RootRank, shown next to results so nobody over-trusts.\n"
        "export const BENCHMARK = {\n" + "\n".join(lines) + "\n} as const;\n"
    )


def write_facts() -> dict[str, str]:
    facts = build_facts()
    FACTS_PATH.write_text(render_facts_ts(facts))
    return facts

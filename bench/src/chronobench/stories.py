"""Evidence-locked stories, measured (``uv run bench stories``; needs a running Ollama).

30 simulated incidents (seeds 6-10 of each of 6 faults; seeds 1-5 were used to build the checker
and prompt and are not reported). A local model writes each story and the engine's checker keeps
only sentences it can verify. Cost is $0 (local); time and tokens are reported instead.
"""

import json
import subprocess
import urllib.request
from collections import Counter

from .evaluate import REPO_ROOT, code_fingerprint
from .runner import ensure_runner_built

ENTRY = REPO_ROOT / "bench" / "runner" / "dist" / "storybench.js"
OLLAMA_URL = "http://localhost:11434"
MODEL = "qwen2.5:3b"  # small, free, runs on a 16 GB laptop; chosen before the first run
REASONS = (
    "uncited", "unknown_fact", "unknown_service", "off_topic_cite",
    "unsupported_number", "unsupported_cause", "malformed",
)  # fmt: skip


def _ollama_version() -> str:
    with urllib.request.urlopen(f"{OLLAMA_URL}/api/version", timeout=5) as res:
        return json.loads(res.read())["version"]


MODEL_SEEDS = (0, 1, 2)  # a local model is not exactly repeatable, so 3 runs give a spread


def _run_once(model: str, seed: int) -> dict:
    done = subprocess.run(
        ["node", str(ENTRY), OLLAMA_URL, model, "test", str(seed)],
        capture_output=True, timeout=3600, check=False,
    )  # fmt: skip
    if done.returncode != 0:
        raise RuntimeError(f"Story runner failed: {done.stderr.decode()}")
    return json.loads(done.stdout)


def _summarise(cases: list[dict]) -> dict:
    total = lambda k: sum(c["stats"][k] for c in cases)  # noqa: E731
    reasons = Counter(d["reason"] for c in cases for d in c["dropped"])
    sentences = total("sentences")
    return {
        "well_formed": sum(c["isWellFormed"] for c in cases),
        "sentences": sentences, "kept": total("kept"),
        "cites": total("cites"), "valid_cites": total("validCites"),
        "citation_precision": total("validCites") / max(total("cites"), 1),
        "uncited_rate": reasons["uncited"] / max(sentences, 1),
        "kept_rate": total("kept") / max(sentences, 1),
        "cases_with_a_kept_sentence": sum(c["stats"]["kept"] > 0 for c in cases),
        "dropped_by_reason": {r: reasons[r] for r in REASONS},
        "median_seconds": sorted(c["seconds"] for c in cases)[len(cases) // 2],
        "mean_prompt_tokens": sum(c["promptTokens"] for c in cases) / len(cases),
        "mean_output_tokens": sum(c["outputTokens"] for c in cases) / len(cases),
        "template_kept": sum(c["template"]["kept"] for c in cases),
        "template_sentences": sum(c["template"]["sentences"] for c in cases),
    }  # fmt: skip


def _spread(runs: list[dict], key: str) -> dict:
    values = [r[key] for r in runs]
    return {"mean": sum(values) / len(values), "min": min(values), "max": max(values)}


def run_stories(model: str = MODEL) -> dict:
    ensure_runner_built()
    raws = [_run_once(model, seed) for seed in MODEL_SEEDS]
    runs = [_summarise(raw["cases"]) for raw in raws]
    first = raws[0]["cases"]
    return {
        "setup": {
            "model": model,
            "model_seeds": list(MODEL_SEEDS),
            "temperature": 0,
            "ollama_version": _ollama_version(),
            "split": raws[0]["split"],
            "cases": len(first),
            "code_fingerprint": code_fingerprint("stories"),
        },  # fmt: skip
        "runs": runs,
        "spread": {
            k: _spread(runs, k) for k in ("citation_precision", "kept_rate", "uncited_rate")
        },
        "examples": [
            {
                "case": c["id"],
                "kept": [s["text"] for s in c["kept"]][:2],
                "dropped": c["dropped"][:2],
            }
            for c in first[::6]
        ],
    }


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render_stories_report(r: dict) -> str:
    s, u, sp = r["setup"], r["runs"][0], r["spread"]
    rng = lambda k: f"{_pct(sp[k]['mean'])} ({_pct(sp[k]['min'])}-{_pct(sp[k]['max'])})"  # noqa: E731
    lines = [
        "# ChronoBench: evidence-locked incident stories\n",
        "Can a small local model write an incident story that only says what the evidence shows? "
        "Generated by `uv run bench stories`; do not edit by hand.\n",
        "## Setup\n",
        f"- **Model:** `{s['model']}` on Ollama {s['ollama_version']}, temperature 0, running "
        f"locally (cost $0). Run {len(s['model_seeds'])} times (model seeds "
        f"{', '.join(map(str, s['model_seeds']))}): a local model does not repeat itself exactly.",
        f"- **Incidents:** {s['cases']} simulated incidents (6 faults x seeds 6-10), RootRank with the "
        "true start. Simulated because real RCAEval lines carry no ids to cite. Seeds 1-5 were used "
        "to write the prompt and the checker and are not reported here.",
        "- **What the model sees:** the top 3 suspects and numbered facts (E1, E2, ...) that the "
        "engine computed, each backed by log ids; never raw logs. It must cite fact keys.",
        "- **The checker drops a sentence** that cites nothing or an unknown key, names a service "
        "that is not a suspect, cites a fact about a service it does not name, uses a number not "
        'in its services\' facts, or gives a reason ("due to", "suggesting", ...) the facts do not state.',
        f"- **Code:** fingerprint `{s['code_fingerprint']}`.\n",
        "## Results\n",
        f"Mean over the {len(s['model_seeds'])} runs, with the range:\n",
        "| Measure | Value |",
        "|---|---|",
        f"| **Citation precision** (cites in kept sentences / all cites) | **{rng('citation_precision')}** |",
        f"| Sentences kept by the checker | {rng('kept_rate')} |",
        f"| Uncited-claim rate (before the checker) | {rng('uncited_rate')} |",
        "| Uncited claims shown in the UI | 0 (the checker removes them) |",
        "",
        "Details of the first run (model seed 0):\n",
        "| Measure | Value |",
        "|---|---|",
        f"| Replies in the asked JSON shape | {u['well_formed']} of {s['cases']} |",
        f"| Sentences written | {u['sentences']} |",
        f"| Sentences kept by the checker | {u['kept']} ({_pct(u['kept_rate'])}) |",
        f"| Incidents with at least one kept sentence | {u['cases_with_a_kept_sentence']} of {s['cases']} |",
        f"| Median time per story | {u['median_seconds']:.1f} s |",
        f"| Mean tokens in / out | {u['mean_prompt_tokens']:.0f} / {u['mean_output_tokens']:.0f} |",
        "| Cost | $0 (local model) |",
        f"| Checker sanity: facts restated as sentences, kept | {u['template_kept']} of {u['template_sentences']} |\n",
        "Dropped sentences by reason (first run):\n",
        "| Reason | Sentences |",
        "|---|---|",
        *[f"| `{k}` | {v} |" for k, v in u["dropped_by_reason"].items()],
        "",
        "## Limits\n",
        "- The checks are mechanical. A kept sentence can still read more into a fact than it says "
        '(seen on the dev seeds: "... indicating it was involved in the issue"). Kept sentences '
        "were not audited by people.",
        "- A local model is not exactly repeatable, even at temperature 0 with a fixed seed, so the "
        "headline is a mean over runs and this report is not byte-identical when re-run. Times "
        "depend on the machine.",
        "- A checker bug was found on the test split after the first report: fact keys written "
        'into a sentence ("... (E4).") counted as unsupported numbers. It was fixed and the '
        "benchmark re-run; before the fix, citation precision was 72.7% and 76.6% of sentences "
        "were kept.",
        "- Simulated incidents have simple, repetitive messages; real logs are harder.",
        "- Stories restate the ranking. If RootRank's top suspect is wrong, the story is wrong too, "
        'and says so only through the words "likely" / "possible".\n',
        "## Examples (first run, every 6th incident)\n",
    ]
    for e in r["examples"]:
        lines.append(f"**{e['case']}**\n")
        lines += [f"- kept: {t}" for t in e["kept"]]
        lines += [f"- dropped ({d['reason']}): {d['text']}" for d in e["dropped"]]
        lines.append("")
    return "\n".join(lines)

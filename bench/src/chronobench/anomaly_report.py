"""Render the anomaly benchmark results as markdown. Generated; never edited by hand."""

LABELS = {
    "always_anomalous": "Always anomalous",
    "random_same_budget": "Random, same flag rate (5 seeds)",
    "severity_rule": "Severity rule (flag error and critical lines)",
    "chronolog_h": "**ChronoLog-H** anomaly rules",
}


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _delay(x: float | None) -> str:
    return "n/a" if x is None else f"{x:+.0f} s"


def _table(result: dict) -> str:
    rows = [
        "| Method | Precision | Recall | F1 | Episodes detected | Median delay |",
        "|---|---|---|---|---|---|",
    ]
    for key, label in LABELS.items():
        m = result["methods"][key]
        found = f"{m['episodes_detected']:.0f} of {m['episodes']:.0f}"
        rows.append(
            f"| {label} | {_pct(m['precision'])} | {_pct(m['recall'])} | {_pct(m['f1'])} "
            f"| {found} | {_delay(m['median_delay_s'])} |"
        )
    return "\n".join(rows)


def render_anomaly_report(results: dict) -> str:
    setup = results["setup"]
    parts = [
        "# ChronoBench: anomaly detection results\n",
        "Can the ChronoLog-H anomaly rules tell abnormal logs from normal ones? "
        "Generated by `uv run bench anomaly`; do not edit by hand.\n",
        "## Setup\n",
        f"- **Data:** {setup['dataset']}. Only the first {setup['prefix_lines']:,} lines of each log "
        "are used (a plain `head`, so no line is picked by label).",
        "- **Unit:** an HDFS block, or a 60 s BGL window. A unit is predicted anomalous if any of its "
        "lines is flagged. Truth: HDFS block labels; a BGL window is anomalous if it has an alarm line.",
        "- **Delay:** per episode (one HDFS block, or a run of anomalous BGL windows), the time from "
        "the first reference line to the first flagged line. Reference: the first alarm line (BGL) or "
        "the block's first log line (HDFS, whose labels carry no time). Negative means flagged early.",
        f"- **Code:** code fingerprint `{setup['code_fingerprint']}`. Severity comes from the log's own "
        "level field. No parameter was tuned on these datasets.\n",
    ]
    for name, result in results["datasets"].items():
        parts.append(f"## {name}\n")
        parts.append(
            f"{result['lines']:,} lines, {result['units']:,} units, {result['anomalous_units']:,} "
            f"anomalous ({_pct(result['base_rate'])}). ChronoLog-H flags "
            f"{_pct(result['chronolog_h_flagged_line_rate'])} of lines.\n"
        )
        parts.append(_table(result) + "\n")
    return "\n".join(parts)

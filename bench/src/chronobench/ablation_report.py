"""Render the RootRank ablation and breakdowns as markdown. Generated; never edited by hand."""

import numpy as np

from .rootrank import SEEDS

VARIANT_NOTE = {
    "only first-error rank": "sanity check: should land near the first-error baseline",
}


def _pct(mean: float, std: float) -> str:
    return f"{100 * mean:.1f}% ± {100 * std:.1f}"


def _ablation_table(variants: dict) -> str:
    full = variants["all features"]["ac3"]
    rows = [
        "| Variant | Features | AC@1 | AC@3 | AC@5 | AC@3 vs all features |",
        "|---|---|---|---|---|---|",
    ]
    for name, v in variants.items():
        delta = "" if name == "all features" else f"{100 * (v['ac3'] - full):+.1f} pts"
        rows.append(
            f"| {name} | {v['features']} | {_pct(v['ac1'], v['ac1_std'])} | {_pct(v['ac3'], v['ac3_std'])} "
            f"| {_pct(v['ac5'], v['ac5_std'])} | {delta} |"
        )
    return "\n".join(rows)


def _hits(ranks: list, k: int) -> np.ndarray:
    return np.array([r is not None and r <= k for r in ranks], dtype=float)


def fault_kind(case: dict) -> str:
    """Train Ticket code faults (f1-f5) redeploy a changed service; the rest are resource faults."""
    return "code fault (f1-f5)" if case["fault"].startswith("f") else "resource fault"


def _breakdown(result: dict, cases: dict, key, order: list[str]) -> str:
    ids = result["case_ids"]
    per_seed = np.array(
        [_hits(r, 3) for r in result["variants"]["all features"]["ranks_by_seed"].values()]
    )
    rootrank = per_seed.mean(axis=0)
    first = np.array(
        [
            cases[i]["methods"]["first_error"]["rank"] is not None
            and cases[i]["methods"]["first_error"]["rank"] <= 3
            for i in ids
        ],
        dtype=float,
    )
    hand = np.array(
        [
            cases[i]["methods"]["chronolog_h"]["rank"] is not None
            and cases[i]["methods"]["chronolog_h"]["rank"] <= 3
            for i in ids
        ],
        dtype=float,
    )
    groups = np.array([key(cases[i]) for i in ids])
    rows = ["| Group | Cases | First error | ChronoLog-H | RootRank |", "|---|---|---|---|---|"]
    for g in order:
        m = groups == g
        if m.any():
            rows.append(
                f"| {g} | {int(m.sum())} | {100 * first[m].mean():.1f}% | {100 * hand[m].mean():.1f}% | {100 * rootrank[m].mean():.1f}% |"
            )
    return "\n".join(rows)


def _code_fault_note(check: dict | None) -> str:
    text = "RootRank solves the Train Ticket code faults perfectly. "
    if check is None:
        return text + "\n"
    return (
        text
        + f"The reason, measured: in {check['restart_like']} of {check['cases']} code-fault cases the faulty service "
        "logs shutdown or startup lines it never logged before, so these faults were injected by restarting or "
        f"redeploying the service. The faulty service logs a median of {check['median_novel_root']:.0f} new messages "
        f"during the incident, against {check['median_novel_other']:.1f} for each other service. RootRank is detecting a "
        "restart, which is a real signal in production too but an artifact of how this benchmark injects these faults. "
        "Resource faults leave far fewer traces in logs, so that row is the harder and more honest number.\n"
    )


def render_ablation_report(result: dict, rcaeval: dict) -> str:
    cases = {c["case_id"]: c for c in rcaeval["cases"]}
    variants = result["variants"]
    faults = sorted({c["fault"] for c in cases.values()})
    parts = [
        "# ChronoBench: RootRank ablation and breakdowns\n",
        "Which signals matter, and where does RootRank win or lose? Generated by `uv run bench ablate`; do not edit by hand.\n",
        "## Setup\n",
        f"- Headline protocol: 5-fold cross-validation over all {len(result['case_ids'])} cases, holding out whole "
        f"(system, root service) groups; mean ± standard deviation over {len(SEEDS)} seeds; {result['rounds']} boosting rounds "
        "(chosen earlier on the train split, not re-tuned here).",
        "- Cases whose root service writes no logs count as misses for every method.\n",
        "## Ablation: AC@3 with feature groups removed or kept alone\n",
        _ablation_table(variants) + "\n",
        "## AC@3 by fault kind\n",
        _code_fault_note(result.get("code_fault_check")),
        _breakdown(result, cases, fault_kind, ["code fault (f1-f5)", "resource fault"]) + "\n",
        "## AC@3 by system\n",
        _breakdown(result, cases, lambda c: c["system"], ["ob", "ss", "tt"]) + "\n",
        "## AC@3 by fault type\n",
        "Groups are small, so treat single differences as hints, not findings. "
        "`f1`-`f5` are Train Ticket code faults; the rest are injected resource faults.\n",
        _breakdown(result, cases, lambda c: c["fault"], faults) + "\n",
    ]
    return "\n".join(parts)

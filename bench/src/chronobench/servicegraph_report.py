"""Render the service-graph results as markdown. Generated; never edited by hand."""

NAMES = {"ob": "Online Boutique", "ss": "Sock Shop"}
KINDS = {
    "mention": "Mention edges (A's logs name B)",
    "correlation": "Correlation edges (volumes move together)",
    "union": "Both",
}


def render_servicegraph_report(result: dict) -> str:
    rows = ["| System | Evidence | Precision | Recall | F1 | Cases |", "|---|---|---|---|---|---|"]
    for system, kinds in result["scores"].items():
        for kind, label in KINDS.items():
            s = kinds[kind]
            rows.append(
                f"| {NAMES[system]} | {label} | {100 * s['precision']:.0f}% | {100 * s['recall']:.0f}% "
                f"| {100 * s['f1']:.0f}% | {s['cases']} |"
            )
    return "\n".join(
        [
            "# ChronoBench: learned service graph\n",
            "Can the service graph be learned from logs alone, and how close is it to the real call graph? "
            "Generated by `uv run bench graph`; do not edit by hand.\n",
            "## Setup\n",
            "- The graph is learned from each case's whole log window, with no incident start and no prior. "
            f"A mention edge needs at least {result['min_mentions']} naming lines; a correlation edge needs a correlation "
            f"of at least {result['min_correlation']} between per-{result['bucket_s']} s line counts.",
            "- Edges are compared as undirected pairs against the call graphs of the two systems, written from their "
            "public architecture docs. They may omit real edges, which would count correct finds as false positives, "
            "so precision is a lower bound.",
            "- **Train Ticket is not scored**: its 47-service call graph is not documented well enough to trust.\n",
            "## Results (mean over cases)\n",
            "\n".join(rows) + "\n",
        ]
    )

"""Render the end-to-end (estimated start) results as markdown. Generated; never edited by hand."""

import numpy as np

from .autostart import STARTS, WITHIN
from .metrics import cluster_bootstrap, group_of


def _row(name: str, variant: dict, case_ids: list[str]) -> str:
    per_seed = np.array(
        [[r is not None and r <= 3 for r in ranks] for ranks in variant["ranks_by_seed"].values()],
        dtype=float,
    )
    mean = per_seed.mean(axis=1)
    low, high = cluster_bootstrap(per_seed.mean(axis=0), [group_of(c) for c in case_ids])
    o = variant["offsets"]
    within = " | ".join(f"{100 * o.get(f'within_{w}s', 0):.0f}%" for w in WITHIN)
    median = f"{o['median_offset_s']:+.0f} s" if "median_offset_s" in o else "n/a"
    return (
        f"| {name} | {100 * mean.mean():.1f}% ± {100 * mean.std():.1f} ({100 * low:.0f}-{100 * high:.0f}) "
        f"| {o['found']} of {o['cases']} | {median} | {within} |"
    )


def render_autostart_report(result: dict) -> str:
    rows = [
        "| Incident start used | AC@3 | Start found | Median offset | Within 30 s | Within 60 s | Within 120 s |",
        "|---|---|---|---|---|---|---|",
    ]
    rows += [_row(n, result["variants"][n], result["case_ids"]) for n in STARTS]
    return "\n".join(
        [
            "# ChronoBench: RootRank with an estimated incident start\n",
            "The benchmark hands every method the true start time; a live system does not have it. "
            "Generated by `uv run bench autostart`; do not edit by hand.\n",
            "## Setup\n",
            f"- All {result['cases']} RCAEval cases, headline protocol (whole root services held out, 5 seeds, "
            f"{result['rounds']} rounds); the model is trained on true-start features.",
            "- Each held-out window is **cropped at random** to 300-720 s before and after the true start "
            "(seeded by case id). Without this, guessing the middle of the window would score perfectly, "
            "because RCAEval windows are symmetric around the start.",
            "- **Estimated start:** the split of the window where log behaviour changes most (a Poisson likelihood-ratio "
            "statistic summed over every service and template; see `startdetect.py`). It needs at least 4 minutes of logs.",
            "- **First-error rule:** the heuristic the API used before ('first error-level line after 20 lines'). "
            "A case where it finds no start counts as a miss.",
            "- Offsets are detected minus true start, over the cases where a start was found.\n",
            "## Results\n",
            "\n".join(rows) + "\n",
            "## What this means\n",
            "- The estimator keeps most of RootRank's accuracy without being told when the incident began.",
            "- The estimator cannot tell a calm window from an incident window (on calm windows it scores about as "
            "high), so the app asks the user, or an alert, to say that something went wrong, and estimates only the start.\n",
        ]
    )

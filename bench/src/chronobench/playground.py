"""Benchmark RootRank on the Fault Playground's simulated incidents, and render the results.

The simulator is ChronoLog's own (packages/engine/src/sim), so this is illustrative: it shows how
the live demo behaves, including that hard faults are close to chance. It is not the benchmark
(that is RCAEval, see RESULTS-rootrank.md).
"""

import json
import subprocess

from .evaluate import REPO_ROOT
from .runner import ensure_runner_built

ENTRY = REPO_ROOT / "bench" / "runner" / "dist" / "simaccuracy.js"
LABELS = {
    "crash": "Crash and restart (easy)",
    "disk": "Disk full (easy)",
    "memory": "Memory pressure (medium)",
    "cpu": "CPU saturation (medium)",
    "delay": "Network delay (hard)",
    "loss": "Packet loss (hard)",
}


def run_playground() -> dict:
    ensure_runner_built()
    done = subprocess.run(["node", str(ENTRY)], capture_output=True, check=False, timeout=1800)
    if done.returncode != 0:
        raise RuntimeError(f"Playground benchmark failed: {done.stderr.decode()}")
    return json.loads(done.stdout)


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.0f}%"


def render_playground_report(result: dict) -> str:
    n_services = result["services"]
    rows = [
        "| Fault | Runs | Top-1, start given | Top-1, start estimated | Top-3, start given | Top-3, start estimated |",
        "|---|---|---|---|---|---|",
    ]
    tallies = {LABELS[k]: v for k, v in result["byFault"].items()} | {
        "**All faults**": result["overall"]
    }
    for label, t in tallies.items():
        n = t["runs"]
        rows.append(
            f"| {label} | {n} | {_pct(t['top1']['given'], n)} | {_pct(t['top1']['estimated'], n)} "
            f"| {_pct(t['top3']['given'], n)} | {_pct(t['top3']['estimated'], n)} |"
        )
    return "\n".join(
        [
            "# ChronoBench: the Fault Playground's simulated incidents\n",
            "How does RootRank behave on the live demo? Generated by `uv run bench playground`; do not edit by hand.\n",
            "## Read this first\n",
            "- The logs are written by ChronoLog's own simulator (`packages/engine/src/sim`): six services, six fault "
            "types, seeded. **This is illustrative. It is not the benchmark**; real accuracy on RCAEval incidents is in "
            "[RESULTS-rootrank.md](RESULTS-rootrank.md).",
            f"- With only {n_services} services, random guessing is right {100 / n_services:.0f}% of the time at top-1 and "
            f"{300 / n_services:.0f}% at top-3. Compare every number below with those.",
            f"- Each row runs every observable (service, fault) pair with {result['seeds']} seeds. A network delay or "
            "packet loss on the gateway leaves no logs at all, so those two combinations are not offered.\n",
            "## Results\n",
            "\n".join(rows) + "\n",
            "## What this shows\n",
            "- Faults that leave their own mark in the broken service's logs (a crash writes startup lines, a full disk "
            "writes errors) are found every time when ChronoLog is told when the fault began. A crash is sometimes missed when "
            "it has to estimate the start, because a brief outage can pull the estimate off.",
            "- Faults that show up only in other services' logs (network delay, packet loss) are close to chance at "
            "top-1, though the true service usually stays in the top 3. The same pattern appears on real incidents.",
        ]
    )
